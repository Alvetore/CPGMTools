/**
 * Get current cyberpsychosis stage by Humanity and EMP
 */
export function getCyberpsychosisStage(humanity: number, emp?: number): CyberpsychosisStage {
  const calculatedEmp = emp !== undefined ? emp : Math.max(0, Math.floor(humanity / 10));

  if (humanity < 0) {
    return CYBERPSYCHOSIS_STAGES.find(s => s.status === 'extreme_cyberpsychosis') || CYBERPSYCHOSIS_STAGES[4];
  }
  if (calculatedEmp === 0) {
    return CYBERPSYCHOSIS_STAGES.find(s => s.status === 'cyberpsychosis') || CYBERPSYCHOSIS_STAGES[3];
  }
  if (calculatedEmp === 1) {
    return CYBERPSYCHOSIS_STAGES.find(s => s.status === 'dissociation') || CYBERPSYCHOSIS_STAGES[2];
  }
  if (calculatedEmp === 2) {
    return CYBERPSYCHOSIS_STAGES.find(s => s.status === 'borderline_dissociation') || CYBERPSYCHOSIS_STAGES[1];
  }
  return CYBERPSYCHOSIS_STAGES.find(s => s.status === 'stable') || CYBERPSYCHOSIS_STAGES[0];
}
